#Даны целые положительные числа A и B (A > B). На отрезке длины A размещено
#максимально возможное количество отрезков длины B (без наложений).
#Используя операцию деления нацело, найти количество отрезков B,
#размещенных на отрезке A.

segment = int(input())
piece = int(input())

count = segment // piece

print(count)