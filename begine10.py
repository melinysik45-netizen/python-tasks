#Begin10 Даны два ненулевых числа. 
# Найти сумму, разность, произведение и частное их квадратов.

a = float(input())
b = float(input())

sum = a ** 2 + b ** 2
difference = a ** 2 - b ** 2
product = a ** 2 * b ** 2
quotient = a ** 2 / b ** 2

print(sum)
print(difference)
print(product)
print(quotient)