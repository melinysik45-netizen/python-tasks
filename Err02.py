#Err2 Прочитать два целых числа и вывести их частное с одним знаком после точки. При делении на ноль
#вывести «Делить на ноль нельзя». Нечисловой ввод обрабатывать не требуется.

try:
    num1 = int(input())
    num2 = int(input())
    div = num1 / num2
    print(f"{div:.1f}")
except ZeroDivisionError:
    print("Делить на ноль нельзя")