#While6 Дано целое число N (> 0). Найти двойной факториал N: N!! = N·(N−2)·(N−4)·… (последний
#сомножитель равен 2, если N — четное, и 1, если N — нечетное). Чтобы избежать целочисленного
#переполнения, вычислять это произведение с помощью вещественной переменной и вывести его
#как вещественное число.

n = int(input())

factorial = 1.0
current = n

while current > 0:
    factorial *= current
    current -= 2
print(factorial)
